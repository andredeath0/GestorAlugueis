    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed

        // 1. Pega os textos que o usuário digitou nas 3 caixinhas
        String locatario = txtLocatario.getText();
        String valor = txtValor.getText();
        String data = txtData.getText();

// Como não tem campo de status na tela, a gente define no código:
        String status = "Pago";

// 2. Verifica se o usuário esqueceu de preencher algo
        if (locatario.isEmpty() || valor.isEmpty() || data.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, preencha todos os campos antes de registrar.");
            return; // Para a execução aqui se tiver vazio
        }

// 3. Pega o controle da Tabela
        javax.swing.table.DefaultTableModel modeloTabela = (javax.swing.table.DefaultTableModel) tblPagamentos.getModel();

// 4. Adiciona a linha na tabela mandando as 4 informações (para as 4 colunas)
        modeloTabela.addRow(new Object[]{
            locatario,
            valor,
            data,
            status // A quarta coluna recebe a palavra "Pago" automaticamente
        });

// 5. Limpa as caixinhas pra ficar pronto pro próximo registro
        txtLocatario.setText("");
        txtValor.setText("");
        txtData.setText("");
        txtLocatario.requestFocus(); // Joga o ponteiro do mouse de volta pro primeiro campo

    }//GEN-LAST:event_btnRegistrarActionPerformed

