    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String nome = txtNome.getText().trim();
        String cpf = txtCpf.getText().trim();
        String telefone = txtTelefone.getText().trim();

        if (nome.isEmpty() || cpf.isEmpty() || telefone.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Atenção: Todos os campos são obrigatórios!",
                    "Erro de Validação",
                    javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        String sql = "INSERT INTO locatario (nome, cpf, telefone) VALUES (?, ?, ?)";

        try (java.sql.Connection con = ConexaoDB.conectar(); java.sql.PreparedStatement stmt = con.prepareStatement(sql)) {

            // Substitui as interrogações pelos dados digitados
            stmt.setString(1, nome);
            stmt.setString(2, cpf);
            stmt.setString(3, telefone);

            // Executa a inserção no MySQL
            stmt.executeUpdate();

            // Atualiza a tabela visual na tela
            javax.swing.table.DefaultTableModel dtm = (javax.swing.table.DefaultTableModel) tabelaLocatarios.getModel();
            carregarTabelaLocatarios();

            javax.swing.JOptionPane.showMessageDialog(this,
                    "Locatário salvo no banco de dados com sucesso!",
                    "Sucesso",
                    javax.swing.JOptionPane.INFORMATION_MESSAGE);

            txtNome.setText("");
            txtCpf.setText("");
            txtTelefone.setText("");
            txtNome.requestFocus();

        } catch (java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Erro ao salvar no banco: " + e.getMessage(),
                    "Erro Crítico",
                    javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

