    private void carregarTabelaLocatarios() {
        javax.swing.table.DefaultTableModel dtm = (javax.swing.table.DefaultTableModel) tabelaLocatarios.getModel();
        dtm.setNumRows(0);

        // O comando SQL para buscar todo mundo
        String sql = "SELECT nome, cpf, telefone FROM locatario";

        try (java.sql.Connection con = ConexaoDB.conectar(); java.sql.PreparedStatement stmt = con.prepareStatement(sql); java.sql.ResultSet rs = stmt.executeQuery()) {

           
            while (rs.next()) {
                dtm.addRow(new Object[]{
                    rs.getString("nome"),
                    rs.getString("cpf"),
                    rs.getString("telefone"),
                    "Editar/Excluir"
                });
            }

        } catch (java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Erro ao carregar os dados: " + e.getMessage(),
                    "Erro Crítico",
                    javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }
